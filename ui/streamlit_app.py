# ── I/O helpers ────────────────────────────────────────────────────────────────

def _read_yaml(path: Path) -> dict:
    if path.exists():
        with open(path, encoding="utf-8") as f:
            return yaml.safe_load(f) or {}
    return {}


def _write_yaml(path: Path, data: dict, header: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        if header:
            f.write(header + "\n\n")
        yaml.dump(data, f, default_flow_style=False, allow_unicode=True, sort_keys=False)


def _read_env() -> dict:
    env: dict[str, str] = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                env[k.strip()] = v.strip()
    return env


def _write_env(env: dict) -> None:
    SECTIONS = [
        ("Job Platforms",    ["NAUKRI_EMAIL", "NAUKRI_PASSWORD", "LINKEDIN_EMAIL", "LINKEDIN_PASSWORD"]),
        ("Notifications",    ["TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID",
                               "GMAIL_SENDER", "GMAIL_RECIPIENT",
                               "GMAIL_CREDENTIALS_PATH", "GMAIL_TOKEN_PATH"]),
        ("Candidate Details",["CANDIDATE_NAME", "CANDIDATE_EMAIL", "CANDIDATE_PHONE"]),
        ("Scheduling",       ["TIMEZONE", "APPLY_DEADLINE_IST"]),
        ("Database",         ["DATABASE_URL"]),
        ("Logging",          ["LOG_LEVEL", "LOG_FILE"]),
    ]
    lines = ["# ─── Nexus — generated by Nexus UI ──────────────────────────────────────────", ""]
    for section, keys in SECTIONS:
        pad = "─" * max(1, 58 - len(section))
        lines.append(f"# ─── {section} {pad}─")
        for k in keys:
            lines.append(f"{k}={env.get(k, '')}")
        lines.append("")
    ENV_FILE.write_text("\n".join(lines), encoding="utf-8")


def _lines(s: str) -> list[str]:
    return [l.strip() for l in s.splitlines() if l.strip()]


# ── Resume parsing ─────────────────────────────────────────────────────────────

def _extract_resume_text(uploaded_file) -> str:
    name = uploaded_file.name.lower()
    raw  = uploaded_file.read()

    if name.endswith(".pdf"):
        try:
            import pdfplumber
            parts: list[str] = []
            with pdfplumber.open(io.BytesIO(raw)) as pdf:
                for page in pdf.pages:
                    text = page.extract_text()
                    if text:
                        parts.append(text)
            return "\n".join(parts)
        except Exception as exc:
            st.warning(f"PDF parse error: {exc}. Try DOCX or Markdown.")
            return ""

    if name.endswith(".docx"):
        try:
            import docx
            doc = docx.Document(io.BytesIO(raw))
            return "\n".join(p.text for p in doc.paragraphs if p.text.strip())
        except Exception as exc:
            st.warning(f"DOCX parse error: {exc}.")
            return ""

    if name.endswith((".md", ".txt")):
        return raw.decode("utf-8", errors="ignore")

    st.warning("Unsupported file type — upload PDF, DOCX, or Markdown.")
    return ""


def _extract_resume_text_bytes(filename: str, raw: bytes) -> str:
    """Same as _extract_resume_text but accepts raw bytes directly."""
    name = filename.lower()
    if name.endswith(".pdf"):
        try:
            import pdfplumber
            parts: list[str] = []
            with pdfplumber.open(io.BytesIO(raw)) as pdf:
                for page in pdf.pages:
                    t = page.extract_text()
                    if t:
                        parts.append(t)
            return "\n".join(parts)
        except Exception:
            return ""
    if name.endswith(".docx"):
        try:
            import docx
            doc = docx.Document(io.BytesIO(raw))
            return "\n".join(p.text for p in doc.paragraphs if p.text.strip())
        except Exception:
            return ""
    if name.endswith((".md", ".txt")):
        return raw.decode("utf-8", errors="ignore")
    return ""


