def _save_profile() -> None:
    skills = _read_yaml(SKILLS_FILE)
    cfg    = _read_yaml(AGENT_CONFIG)
    env    = _read_env()

    pref_locs = [l.strip() for l in st.session_state["wz_locs"].split(",") if l.strip()]
    skills["profile"] = {
        "name":             st.session_state["wz_name"],
        "title":            st.session_state["wz_title"],
        "location":         st.session_state["wz_location"],
        "experience_years": st.session_state["wz_exp"],
        "email":            st.session_state["wz_email"],
    }
    skills["summary"]     = st.session_state["wz_summary"]
    skills["preferences"] = {
        "preferred_locations": pref_locs,
        "remote_ok":           st.session_state["wz_remote_ok"],
        "relocation_ok":       st.session_state["wz_relocation_ok"],
        "notice_period_days":  st.session_state["wz_notice"],
    }
    _write_yaml(SKILLS_FILE, skills,
        "# ─── Nexus Skills Profile ────────────────────────────────────────────────────\n"
        "# Rate each skill 1–10. The Scorer uses these weights against job requirements.")

    cfg.setdefault("system", {})["timezone"] = st.session_state["wz_timezone"]
    cfg.setdefault("schedule", {}).update({
        "scout_start":    st.session_state["wz_scout_start"],
        "apply_deadline": st.session_state["wz_deadline"],
    })
    cfg.setdefault("apply", {})["candidate_experience_years"] = st.session_state["wz_exp"]
    _write_yaml(AGENT_CONFIG, cfg, "# ─── Nexus Agent Configuration ──────────────────────────────────────────────")

    env.update({
        "CANDIDATE_NAME":  st.session_state["wz_name"],
        "CANDIDATE_EMAIL": st.session_state["wz_email"],
        "CANDIDATE_PHONE": st.session_state["wz_phone"],
        "TIMEZONE":        st.session_state["wz_timezone"],
        "APPLY_DEADLINE_IST": st.session_state["wz_deadline"],
    })
    env.setdefault("DATABASE_URL", "sqlite:///db/nexus.db")
    env.setdefault("LOG_LEVEL", "INFO")
    env.setdefault("LOG_FILE", "logs/nexus.log")
    _write_env(env)


