def page_advanced() -> None:
    st.title("Advanced Settings")
    cfg      = _read_yaml(AGENT_CONFIG)
    apply_cfg = cfg.get("apply", {})
    llm_cfg  = cfg.get("llm", {})
    scout_cfg = cfg.get("scout", {})
    sched_cfg = cfg.get("schedule", {})

    with st.form("advanced_form"):
        st.subheader("Apply Behaviour")
        c1, c2 = st.columns(2)
        with c1:
            live_mode = st.toggle("Live Mode — submits real applications",
                                  value=apply_cfg.get("live_mode", False),
                                  help="Keep OFF until tested with --dry-run")
            headless  = st.checkbox("Headless Browser", value=apply_cfg.get("headless", True))
        with c2:
            retry   = st.number_input("Retry Attempts",      0, 10,   int(apply_cfg.get("retry_attempts",2)))
            slow_mo = st.number_input("Browser Slow-Mo (ms)",0, 2000, int(apply_cfg.get("slow_mo_ms",50)), step=10)
        captcha_opts = ["skip_and_flag","pause_for_human","abort"]
        captcha = st.selectbox("On CAPTCHA", captcha_opts,
                               index=captcha_opts.index(apply_cfg.get("on_captcha","skip_and_flag")))

        st.subheader("Ollama LLM (Scorer)")
        c1, c2, c3 = st.columns(3)
        with c1: ollama_url    = st.text_input("Base URL", value=llm_cfg.get("base_url","http://localhost:11434"))
        with c2: scorer_model  = st.text_input("Model",    value=llm_cfg.get("scorer_model","llama3.2"))
        with c3: temperature   = st.slider("Temperature", 0.0, 1.0, float(llm_cfg.get("temperature",0.3)), step=0.05)

        st.subheader("Scout")
        c1, c2 = st.columns(2)
        with c1: max_jobs = st.number_input("Max Jobs per Run",       10, 500, int(scout_cfg.get("max_jobs_per_run",100)))
        with c2: interval = st.number_input("Scout Interval (minutes)", 5, 120, int(sched_cfg.get("scout_interval_minutes",30)))

        submitted = st.form_submit_button("Save Advanced Settings", type="primary")

    if submitted:
        if live_mode and not apply_cfg.get("live_mode", False):
            st.warning("Live mode is now ON — Nexus will submit real applications on the next run.")
        cfg.setdefault("apply", {}).update({
            "live_mode": live_mode, "headless": headless,
            "retry_attempts": int(retry), "slow_mo_ms": int(slow_mo), "on_captcha": captcha,
        })
        cfg.setdefault("llm", {}).update({
            "base_url": ollama_url, "scorer_model": scorer_model, "temperature": float(temperature),
        })
        cfg.setdefault("scout", {})["max_jobs_per_run"] = int(max_jobs)
        cfg.setdefault("schedule", {})["scout_interval_minutes"] = int(interval)
        _write_yaml(AGENT_CONFIG, cfg, "# ─── Nexus Agent Configuration ──────────────────────────────────────────────")
        st.success("Advanced settings saved.")


