def _parse_with_ollama(text: str) -> dict:
    try:
        import ollama
        response = ollama.chat(
            model="llama3.2",
            messages=[{"role": "user", "content": _EXTRACTION_PROMPT.format(text=text[:8000])}],
            options={"temperature": 0.1},
        )
        raw   = response["message"]["content"]
        match = re.search(r"\{.*\}", raw, re.DOTALL)
        if match:
            return json.loads(match.group())
    except Exception:
        pass
    return {}


def _parse_with_regex(text: str) -> dict:
    result: dict = {}
    if m := re.search(r"[\w.+\-]+@[\w\-]+\.[a-zA-Z]{2,}", text):
        result["email"] = m.group()
    if m := re.search(r"(\+\d[\d\s\-]{8,15})", text):
        result["phone"] = m.group().strip()
    if m := re.search(r"(\d{1,2})[\s\-]year", text, re.IGNORECASE):
        result["experience_years"] = int(m.group(1))
    for line in text.splitlines():
        line = line.strip().lstrip("#").strip()
        if line and not re.search(r"[@|/\\]", line) and 1 < len(line.split()) <= 6:
            result["name"] = line
            break
    return result


def _parse_resume(uploaded_file) -> dict:
    text = _extract_resume_text(uploaded_file)
    if not text:
        return {}
    with st.spinner("Parsing resume with Ollama…"):
        parsed = _parse_with_ollama(text)
    if not parsed:
        st.info("Ollama unavailable — using basic extraction. Skills will use defaults.")
        parsed = _parse_with_regex(text)
    return parsed


