def _apply_resume_to_state(parsed: dict) -> None:
    """Overwrite wizard session_state with resume-parsed data (all steps)."""
    # Step 1 — Profile
    mapping = {
        "name": "wz_name", "email": "wz_email", "phone": "wz_phone",
        "title": "wz_title", "location": "wz_location", "summary": "wz_summary",
    }
    for src, dst in mapping.items():
        if parsed.get(src):
            st.session_state[dst] = parsed[src]
    if parsed.get("experience_years"):
        st.session_state["wz_exp"] = int(parsed["experience_years"])
    if parsed.get("preferred_locations"):
        st.session_state["wz_locs"] = ", ".join(parsed["preferred_locations"])

    # Step 2 — Career Paths (LLM-extracted)
    career = parsed.get("career", {})
    if career.get("path_b_titles"):
        st.session_state["wz_pb_titles"] = "\n".join(career["path_b_titles"])
    if career.get("path_a_titles"):
        st.session_state["wz_pa_titles"] = "\n".join(career["path_a_titles"])
    if career.get("search_keywords"):
        st.session_state["wz_keywords"] = "\n".join(career["search_keywords"])
    if career.get("strong_positives"):
        st.session_state["wz_sig_sp"] = "\n".join(career["strong_positives"])
    if career.get("mild_positives"):
        st.session_state["wz_sig_mp"] = "\n".join(career["mild_positives"])
    if career.get("strong_negatives"):
        st.session_state["wz_sig_sn"] = "\n".join(career["strong_negatives"])
    if career.get("mild_negatives"):
        st.session_state["wz_sig_mn"] = "\n".join(career["mild_negatives"])

    # Step 3 — Skills
    for cat_key, skill_key, _, _ in _SKILLS:
        rating = parsed.get("skills", {}).get(cat_key, {}).get(skill_key)
        if rating is not None:
            st.session_state[_sk(cat_key, skill_key)] = int(rating)


